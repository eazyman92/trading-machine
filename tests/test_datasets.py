def sample():
    rows=['time,bid_open,bid_high,bid_low,bid_close,spread']
    day=datetime(2025,1,6,7,tzinfo=timezone.utc)
    for _ in range(10):
        while day.weekday()>4:day+=timedelta(days=1)
        for i in range(541):rows.append((day+timedelta(minutes=i)).isoformat()+',2000,2000.01,1999.99,2000,0.20')
        day+=timedelta(days=1)
    return '\n'.join(rows)

