def test_registry_integrity_and_chronology(env):
    text=sample();item=register(text,'Synthetic qualification test only','Generated by test, no market prices')
    assert read(item['id'])==text and item['quality']['selected_rows']==5410
    plan=split_plan(item['id']);periods=plan['periods']
    assert [p['eligible_sessions'] for p in periods.values()]==[6,2,2]
    assert periods['development']['end_date']<periods['validation']['start_date']<periods['holdout']['start_date']
    assert register(text,'Different later claim','Do not overwrite prior provenance')['source']==item['source']
    with pytest.raises(ValueError):paths('../escape')
    paths(item['id'])[0].write_text('corrupt')
    with pytest.raises(ValueError):read(item['id'])

def test_stored_dataset_job_and_progress(env):
    store=Store()
    with TestClient(app) as client:
        response=client.post('/api/v1/research/datasets',json={'csv_text':sample(),'source':'Synthetic long CSV engineering test','rights_reference':'Generated locally for engineering tests','rights_confirmed':True})
        assert response.status_code==201,response.text
        dataset=response.json()['id']
        assert client.get('/api/v1/research/datasets').json()['items'][0]['id']==dataset
        assert client.get('/api/v1/research/datasets/'+dataset+'/split-plan').status_code==200
        body={'dataset_id':dataset,'spec':dict(tick_usd='.01',ounces_per_lot='100',lot_step='.01',minimum_lots='.01',commission_usd_per_lot_side='7',risk_budget_usd='25',notional_cap_usd='10000')}
        job=client.post('/api/v1/research/gold/stored-jobs',json=body,headers={'Idempotency-Key':str(uuid.uuid4())})
        assert job.status_code==202,job.text
        assert 'csv_text' not in job.json()['config']
        assert process_one(store)
        done=store.get(job.json()['id'])
        assert done['status']=='completed' and done['result']['bar_count']==5410
        assert done['result']['dataset_sha256']==dataset

def test_heartbeat_cannot_revive_cancelled_or_expired_work(env):
    store=Store();job=store.create(str(uuid.uuid4()),{})
    store.claim()
    assert store.heartbeat(job['id'],{'stage':'replaying','done':1,'total':10})
    assert store.get(job['id'])['result']['progress']['done']==1
    store.cancel(job['id'])
    assert not store.heartbeat(job['id'])
    job=store.create(str(uuid.uuid4()),{});store.claim()
    with store.connection() as conn:store.sql(conn,'UPDATE research_jobs SET lease_until=0 WHERE id=?',(job['id'],))
    assert not store.heartbeat(job['id'])
